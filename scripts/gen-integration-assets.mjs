#!/usr/bin/env node
/**
 * Inlines each agent-integration source file into a TypeScript module the CLI
 * bundle can carry (T-308).
 *
 * `todou` ships as one esbuild-produced .cjs and four `deno compile`
 * executables. Neither form takes a resource file along, so an extension that
 * `integration install` writes to disk has to already be inside the binary as
 * a string. Keeping the real source in a real file — checked by tsc, linted,
 * highlighted — and generating the string from it is what buys that without
 * writing the extension inside a template literal; `asset-sync.test.ts` is
 * what keeps the two copies from drifting.
 *
 * Run it with `pnpm gen` (or directly); `--check` reports drift without
 * writing, which is what the test uses. Run it *after* `pnpm fmt`, since
 * formatting the real source is itself a change the generated copy has to
 * follow — the sync test says so when the order slips.
 *
 * biome does not format the output (see the `*.generated.ts` override in
 * biome.json), so the shape below is the only one there is to match: a
 * formatter that reflowed it would fight this script over every run.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** One entry per integration: where the source is, and what to call it. */
export const ASSETS = [
  {
    source: "projects/cli/src/integrations/omp/extension.ts",
    output: "projects/cli/src/integrations/omp/extension.generated.ts",
    constant: "OMP_EXTENSION_SOURCE",
    describe: "the omp extension",
  },
];

/** What the generated module should contain, given the source it inlines. */
export function render(asset, source) {
  return [
    `// Generated by scripts/gen-integration-assets.mjs — do not edit.`,
    `// Source: ${asset.source}`,
    ``,
    `/** ${asset.describe}, verbatim, for a bundle that carries no files. */`,
    `export const ${asset.constant} =`,
    `  ${JSON.stringify(source)};`,
    ``,
  ].join("\n");
}

/** Every asset's expected output, read from the working tree. */
export function generate() {
  return ASSETS.map((asset) => ({
    asset,
    path: join(root, asset.output),
    want: render(asset, readFileSync(join(root, asset.source), "utf8")),
  }));
}

function main(argv) {
  const check = argv.includes("--check");
  let drifted = 0;
  for (const { asset, path, want } of generate()) {
    let have;
    try {
      have = readFileSync(path, "utf8");
    } catch {
      have = null;
    }
    if (have === want) continue;
    drifted += 1;
    if (check) {
      console.error(
        `${relative(root, path)} is stale — run node scripts/gen-integration-assets.mjs`,
      );
      continue;
    }
    writeFileSync(path, want);
    console.log(`wrote ${relative(root, path)} from ${asset.source}`);
  }
  if (check && drifted > 0) process.exit(1);
  if (!check && drifted === 0)
    console.log("integration assets already current");
}

// Importable by the test without running: it needs `generate`, not the CLI.
if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv);
